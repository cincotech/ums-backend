@api_view(["GET"])
@permission_classes([IsAuthenticated, IsDean])
def academic_performance_report(request):
    """
    Générer un rapport de performance académique.
    
    Query params:
        - academic_year: Année académique (optionnel, défaut: année active)
        - format: 'summary' ou 'detailed' (défaut: 'summary')
    """
    academic_year_id = request.query_params.get("academic_year")
    report_format = request.query_params.get("format", "summary")

    report = AcademicDashboardService.get_academic_performance_report(
        academic_year_id=academic_year_id,
        format=report_format,
    )
    return Response(report)


@api_view(["GET"])
@permission_classes([IsAuthenticated, IsDean])
def suggestions_list(request):
    """
    Lister toutes les suggestions ou les suggestions en attente.
    
    Query params:
        - attribution_id: Filtrer par attribution
        - status: 'pending', 'all' (défaut: 'pending')
    """
    attribution_id = request.query_params.get("attribution_id")
    status_filter = request.query_params.get("status", "pending")

    suggestions = Suggestion.objects.all()

    if attribution_id:
        suggestions = suggestions.filter(attribution_id=attribution_id)

    if status_filter != "all":
        # Les suggestions sont liées aux attributions validées
        # donc on filtre par le statut de validation de l'attribution
        suggestions = suggestions.filter(
            attribution__validation_status="approved"
        )

    suggestions = suggestions.select_related(
        "attribution",
        "attribution__course",
        "teacher",
        "teacher__user",
        "user",
    )

    serializer = SuggestionSerializer(suggestions, many=True)
    return Response(serializer.data)


