@api_view(["GET"])
@permission_classes([IsAuthenticated, IsDean])
def dashboard_overview(request):
    """
    Vue d'ensemble académique avec statistiques complètes.
    
    Returns:
        - total_attributions: Nombre total d'attributions
        - pending_attributions: Attributions en attente de validation
        - approved_attributions: Attributions approuvées
        - rejected_attributions: Attributions rejetées
        - total_suggestions: Nombre total de suggestions
        - pending_suggestions: Suggestions en attente
        - validation_rate: Pourcentage de validation
        - attributions_by_status: Répartition par statut
    """
    overview = AcademicDashboardService.get_academic_overview()
    serializer = AcademicOverviewSerializer(overview)
    return Response(serializer.data)


@api_view(["POST"])
@permission_classes([IsAuthenticated, IsDean])
def validate_attribution(request, attribution_id):
    """
    Valider ou rejeter une attribution.
    
    POST body:
        - validation_status: 'approved' ou 'rejected'
        - comments: Commentaires optionnels
    """
    try:
        attribution = Attribution.objects.get(id=attribution_id)
    except Attribution.DoesNotExist:
        return Response(
            {"error": "Attribution not found"},
            status=status.HTTP_404_NOT_FOUND
        )

    serializer = AttributionValidationSerializer(data=request.data)
    serializer.is_valid(raise_exception=True)

    # Mettre à jour l'attribution
    attribution.validation_status = serializer.validated_data["validation_status"]
    attribution.validation_comments = serializer.validated_data.get("comments", "")
    attribution.validated_by = request.user
    attribution.validation_date = timezone.now()
    attribution.save()

    return Response(AttributionSerializer(attribution).data)


@api_view(["GET"])
@permission_classes([IsAuthenticated, IsDean])
def pending_attributions(request):
    """
    Lister les attributions en attente de validation.
    
    Query params:
        - academic_year: Filtrer par année académique (optionnel)
        - principal_teacher: Filtrer par enseignant principal (optionnel)
    """
    academic_year_id = request.query_params.get("academic_year")
    principal_teacher_id = request.query_params.get("principal_teacher")

    attributions = Attribution.objects.filter(validation_status="pending")

    if academic_year_id:
        attributions = attributions.filter(academic_year_id=academic_year_id)
    if principal_teacher_id:
        attributions = attributions.filter(principal_teacher_id=principal_teacher_id)

    attributions = attributions.select_related(
        "course",
        "principal_teacher",
        "principal_teacher__user",
        "substitute_teacher",
        "substitute_teacher__user",
        "academic_year",
    )

    serializer = AttributionSerializer(attributions, many=True)
    return Response(serializer.data)


@api_view(["POST"])
@permission_classes([IsAuthenticated, IsDean])
def add_suggestion(request, attribution_id):
    """
    Ajouter une suggestion après validation de l'attribution.
    
    POST body:
        - suggestion: Texte de la suggestion
    """
    try:
        attribution = Attribution.objects.get(id=attribution_id)
    except Attribution.DoesNotExist:
        return Response(
            {"error": "Attribution not found"},
            status=status.HTTP_404_NOT_FOUND
        )

    # Vérifier que l'attribution est déjà validée
    if attribution.validation_status == "pending":
        return Response(
            {"error": "Attribution must be validated before adding suggestions"},
            status=status.HTTP_400_BAD_REQUEST
        )

    serializer = SuggestionCreateSerializer(data=request.data)
    serializer.is_valid(raise_exception=True)

    # Créer la suggestion
    suggestion = Suggestion.objects.create(
        suggestion_date=timezone.now().date(),
        suggestion=serializer.validated_data["suggestion"],
        attribution=attribution,
        teacher=attribution.principal_teacher,
        user=request.user,
    )

    return Response(SuggestionSerializer(suggestion).data, status=status.HTTP_201_CREATED)


